#!/usr/bin/env node
// Writes the allergen dictionary (packages/verdict-engine/data/dictionary.json) as a SQL migration
// that upserts allergens, allergen_terms and dictionary_meta. The JSON file is the source of truth:
// edit it (for example to mark terms reviewed), then run `npm run gen:dictionary`. In pantry-app
// the npm script passes --out supabase/migrations/007_allergy_dictionary.sql, so it rewrites that file.
//
// Usage: node scripts/gen-dictionary-sql.mjs [--out <file>]

import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const compact = JSON.parse(readFileSync(join(root, 'packages/verdict-engine/data/dictionary.json'), 'utf8'));

const q = (v) => (v === null || v === undefined ? 'null' : `'${String(v).replace(/'/g, "''")}'`);
const slug = (s) =>
  s.normalize('NFKD').replace(/[̀-ͯ]/g, '').toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');

const rows = [];
for (const g of compact.groups) {
  for (const t of g.terms) {
    const spec = typeof t === 'string' ? { term: t } : t;
    for (const allergenId of spec.allergenIds ?? g.allergenIds) {
      rows.push({
        id: `${allergenId}:${slug(spec.term)}`,
        allergen_id: allergenId,
        term: spec.matchType === 'regex' ? spec.term : spec.term.toLowerCase(),
        match_type: spec.matchType ?? 'word',
        strength: spec.strength ?? g.strength,
        scope: spec.scope ?? g.scope ?? 'any',
        source_url: g.sourceUrl,
        reviewed: g.reviewed,
        added_by: g.addedBy,
        note: spec.note ?? g.note ?? null,
      });
    }
  }
}
const missing = rows.filter((r) => !r.source_url);
if (missing.length) {
  console.error(`Refusing to write: ${missing.length} terms have no source_url, e.g. ${missing[0].id}`);
  process.exit(1);
}

const lines = [];
lines.push(`-- Generated by scripts/gen-dictionary-sql.mjs from dictionary.json version ${compact.version}. Do not edit.`);
lines.push('begin;');
lines.push('insert into public.allergens (id, display_name, is_us_major, includes) values');
lines.push(
  compact.allergens
    .map((a) => `  (${q(a.id)}, ${q(a.displayName)}, ${a.isUsMajor}, array[${(a.includes ?? []).map(q).join(', ')}]::text[])`)
    .join(',\n') +
    '\non conflict (id) do update set display_name = excluded.display_name, is_us_major = excluded.is_us_major, includes = excluded.includes;',
);
lines.push('delete from public.allergen_terms;');
lines.push('insert into public.allergen_terms (id, allergen_id, term, match_type, strength, scope, source_url, reviewed, added_by, note) values');
lines.push(
  rows
    .map(
      (r) =>
        `  (${q(r.id)}, ${q(r.allergen_id)}, ${q(r.term)}, ${q(r.match_type)}, ${q(r.strength)}, ${q(r.scope)}, ${q(r.source_url)}, ${r.reviewed}, ${q(r.added_by)}, ${q(r.note)})`,
    )
    .join(',\n') + ';',
);
const meta = {
  version: compact.version,
  advisory_phrases: compact.advisoryPhrases,
  vague_terms: compact.vagueTerms,
  off_tag_map: compact.offTagMap,
};
lines.push('insert into public.dictionary_meta (key, value) values');
lines.push(
  Object.entries(meta)
    .map(([k, v]) => `  (${q(k)}, ${q(JSON.stringify(v))}::jsonb)`)
    .join(',\n') + '\non conflict (key) do update set value = excluded.value, updated_at = now();',
);
lines.push('commit;');

const outIdx = process.argv.indexOf('--out');
let out;
if (outIdx > 0) {
  out = process.argv[outIdx + 1];
} else {
  const migrations = join(root, 'supabase/migrations');
  const existing = readdirSync(migrations).find((f) => f.endsWith(`_dictionary_${compact.version.replace(/\W/g, '_')}.sql`));
  out = join(migrations, existing ?? `${new Date().toISOString().replace(/\D/g, '').slice(0, 14)}_dictionary_${compact.version.replace(/\W/g, '_')}.sql`);
}
writeFileSync(out, lines.join('\n') + '\n');
console.log(`Wrote ${rows.length} terms to ${out}`);
